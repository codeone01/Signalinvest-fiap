-- Execute com F5 no SQL Developer, conectado ao mesmo schema usado pela aplicação.
-- Este arquivo é somente leitura: não cria, altera ou exclui objetos.

SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS BANCO,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICO,
       USER AS SCHEMA_ATUAL
FROM DUAL;

SELECT TABLE_NAME, COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH,
       DATA_PRECISION, DATA_SCALE, NULLABLE, DATA_DEFAULT, IDENTITY_COLUMN
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('TB_USUARIO', 'TB_CONTA_BANCARIA', 'TB_RECEITA', 'TB_DESPESA')
ORDER BY TABLE_NAME, COLUMN_ID;

SELECT C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE, C.STATUS,
       CC.POSITION, CC.COLUMN_NAME, C.R_CONSTRAINT_NAME, C.SEARCH_CONDITION_VC
FROM USER_CONSTRAINTS C
JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
WHERE C.TABLE_NAME IN ('TB_USUARIO', 'TB_CONTA_BANCARIA', 'TB_RECEITA', 'TB_DESPESA')
ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME, CC.POSITION;

SELECT TABLE_NAME, COLUMN_NAME, GENERATION_TYPE, SEQUENCE_NAME, IDENTITY_OPTIONS
FROM USER_TAB_IDENTITY_COLS
WHERE TABLE_NAME IN ('TB_USUARIO', 'TB_CONTA_BANCARIA', 'TB_RECEITA', 'TB_DESPESA')
ORDER BY TABLE_NAME, COLUMN_NAME;

SELECT SEQUENCE_NAME, MIN_VALUE, MAX_VALUE, INCREMENT_BY, CACHE_SIZE,
       LAST_NUMBER, CYCLE_FLAG, ORDER_FLAG
FROM USER_SEQUENCES
WHERE SEQUENCE_NAME IN ('SQ_SI_CONTA', 'SQ_SI_RECEITA', 'SQ_SI_DESPESA')
   OR SEQUENCE_NAME LIKE '%CONTA%'
   OR SEQUENCE_NAME LIKE '%RECEITA%'
   OR SEQUENCE_NAME LIKE '%DESPESA%'
ORDER BY SEQUENCE_NAME;

SELECT TRIGGER_NAME, TABLE_NAME, STATUS, TRIGGER_TYPE, TRIGGERING_EVENT,
       WHEN_CLAUSE, DESCRIPTION, TRIGGER_BODY
FROM USER_TRIGGERS
WHERE TABLE_NAME IN ('TB_USUARIO', 'TB_CONTA_BANCARIA', 'TB_RECEITA', 'TB_DESPESA')
ORDER BY TABLE_NAME, TRIGGER_NAME;

SELECT 'TB_USUARIO' AS TABELA, COUNT(*) AS TOTAL, MAX(ID_USUARIO) AS MAIOR_ID
FROM TB_USUARIO
UNION ALL
SELECT 'TB_CONTA_BANCARIA', COUNT(*), MAX(ID_CONTA) FROM TB_CONTA_BANCARIA
UNION ALL
SELECT 'TB_RECEITA', COUNT(*), MAX(ID_RECEITA) FROM TB_RECEITA
UNION ALL
SELECT 'TB_DESPESA', COUNT(*), MAX(ID_DESPESA) FROM TB_DESPESA;
