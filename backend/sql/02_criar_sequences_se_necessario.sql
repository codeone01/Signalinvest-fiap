-- Execute somente se 00_inspecao_schema.sql comprovar que as três colunas não são
-- identity e que estas sequences ainda não existem. O início é calculado acima do
-- maior ID preservado. O bloco não altera sequences já existentes.

DECLARE
    V_EXISTE NUMBER;
    V_INICIO NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_EXISTE FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SQ_SI_CONTA';
    IF V_EXISTE = 0 THEN
        SELECT NVL(MAX(ID_CONTA), 0) + 1 INTO V_INICIO FROM TB_CONTA_BANCARIA;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_SI_CONTA START WITH ' || V_INICIO || ' INCREMENT BY 1 NOCYCLE NOCACHE';
    END IF;

    SELECT COUNT(*) INTO V_EXISTE FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SQ_SI_RECEITA';
    IF V_EXISTE = 0 THEN
        SELECT NVL(MAX(ID_RECEITA), 0) + 1 INTO V_INICIO FROM TB_RECEITA;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_SI_RECEITA START WITH ' || V_INICIO || ' INCREMENT BY 1 NOCYCLE NOCACHE';
    END IF;

    SELECT COUNT(*) INTO V_EXISTE FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SQ_SI_DESPESA';
    IF V_EXISTE = 0 THEN
        SELECT NVL(MAX(ID_DESPESA), 0) + 1 INTO V_INICIO FROM TB_DESPESA;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_SI_DESPESA START WITH ' || V_INICIO || ' INCREMENT BY 1 NOCYCLE NOCACHE';
    END IF;
END;
/
