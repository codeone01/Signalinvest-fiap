-- Use somente em schema sem as tabelas financeiras, após executar 00_inspecao_schema.sql.
-- TB_USUARIO deve existir. Este script não contém DROP nem COMMIT.

CREATE TABLE TB_CONTA_BANCARIA (
    ID_CONTA NUMBER(10) NOT NULL,
    ID_USUARIO NUMBER(10) NOT NULL,
    NM_BANCO VARCHAR2(100) NOT NULL,
    NR_AGENCIA VARCHAR2(20) NOT NULL,
    NR_CONTA VARCHAR2(30) NOT NULL,
    TP_CONTA VARCHAR2(30) NOT NULL,
    VL_SALDO NUMBER(14,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TB_CONTA_BANCARIA PRIMARY KEY (ID_CONTA),
    CONSTRAINT FK_CONTA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES TB_USUARIO (ID_USUARIO),
    CONSTRAINT UK_CONTA_USUARIO UNIQUE (ID_CONTA, ID_USUARIO)
);

CREATE TABLE TB_RECEITA (
    ID_RECEITA NUMBER(10) NOT NULL,
    ID_USUARIO NUMBER(10) NOT NULL,
    ID_CONTA NUMBER(10) NOT NULL,
    DS_RECEITA VARCHAR2(200) NOT NULL,
    VL_RECEITA NUMBER(14,2) NOT NULL,
    DT_RECEITA DATE NOT NULL,
    TP_RECEITA VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_TB_RECEITA PRIMARY KEY (ID_RECEITA),
    CONSTRAINT FK_RECEITA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES TB_USUARIO (ID_USUARIO),
    CONSTRAINT FK_RECEITA_CONTA_USUARIO FOREIGN KEY (ID_CONTA, ID_USUARIO)
        REFERENCES TB_CONTA_BANCARIA (ID_CONTA, ID_USUARIO),
    CONSTRAINT CK_RECEITA_VALOR CHECK (VL_RECEITA > 0)
);

CREATE TABLE TB_DESPESA (
    ID_DESPESA NUMBER(10) NOT NULL,
    ID_USUARIO NUMBER(10) NOT NULL,
    ID_CONTA NUMBER(10) NOT NULL,
    DS_DESPESA VARCHAR2(200) NOT NULL,
    VL_DESPESA NUMBER(14,2) NOT NULL,
    DT_DESPESA DATE NOT NULL,
    TP_DESPESA VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_TB_DESPESA PRIMARY KEY (ID_DESPESA),
    CONSTRAINT FK_DESPESA_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES TB_USUARIO (ID_USUARIO),
    CONSTRAINT FK_DESPESA_CONTA_USUARIO FOREIGN KEY (ID_CONTA, ID_USUARIO)
        REFERENCES TB_CONTA_BANCARIA (ID_CONTA, ID_USUARIO),
    CONSTRAINT CK_DESPESA_VALOR CHECK (VL_DESPESA > 0)
);
